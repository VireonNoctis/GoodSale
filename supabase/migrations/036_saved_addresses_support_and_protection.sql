-- 036 — Complete the saved-address, support and Buyer Protection data domains.
-- These tables were referenced by application routes but were missing from
-- the checked-in schema. Writes are performed through scoped SECURITY DEFINER
-- functions so clients never receive generic write access.
BEGIN;

CREATE TABLE IF NOT EXISTS public.buyer_addresses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  label text NOT NULL DEFAULT 'Home',
  contact_name text NOT NULL,
  phone text NOT NULL,
  state text NOT NULL,
  city text NOT NULL,
  area text NOT NULL DEFAULT '',
  street text NOT NULL,
  landmark text NOT NULL DEFAULT '',
  instructions text NOT NULL DEFAULT '',
  lat double precision,
  lng double precision,
  is_default boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT buyer_addresses_lat_range CHECK (lat IS NULL OR lat BETWEEN -90 AND 90),
  CONSTRAINT buyer_addresses_lng_range CHECK (lng IS NULL OR lng BETWEEN -180 AND 180)
);
CREATE INDEX IF NOT EXISTS idx_buyer_addresses_profile_updated
  ON public.buyer_addresses(profile_id, is_default DESC, updated_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_buyer_addresses_one_default
  ON public.buyer_addresses(profile_id) WHERE is_default = true;
ALTER TABLE public.buyer_addresses ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS buyer_addresses_owner_read ON public.buyer_addresses;
CREATE POLICY buyer_addresses_owner_read ON public.buyer_addresses
  FOR SELECT TO authenticated USING (profile_id = public.current_profile_id());

CREATE TABLE IF NOT EXISTS public.support_tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference text NOT NULL UNIQUE,
  user_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  user_name text NOT NULL DEFAULT '',
  category text NOT NULL CHECK (category IN ('PAYMENT','DELIVERY','ACCOUNT','REFUND','SELLER_DISPUTE','OTHER')),
  subject text NOT NULL,
  description text NOT NULL,
  order_id bigint REFERENCES public.orders(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'OPEN',
  priority text NOT NULL DEFAULT 'NORMAL' CHECK (priority IN ('LOW','NORMAL','HIGH')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_support_tickets_user_updated
  ON public.support_tickets(user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_support_tickets_status_created
  ON public.support_tickets(status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.support_ticket_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES public.support_tickets(id) ON DELETE CASCADE,
  author_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  author_name text NOT NULL DEFAULT '',
  author_role text NOT NULL DEFAULT 'BUYER',
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_support_ticket_messages_ticket_created
  ON public.support_ticket_messages(ticket_id, created_at ASC);

ALTER TABLE public.support_tickets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_ticket_messages ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS support_tickets_owner_read ON public.support_tickets;
CREATE POLICY support_tickets_owner_read ON public.support_tickets
  FOR SELECT TO authenticated USING (user_id = public.current_profile_id() OR public.is_admin());
DROP POLICY IF EXISTS support_ticket_messages_owner_read ON public.support_ticket_messages;
CREATE POLICY support_ticket_messages_owner_read ON public.support_ticket_messages
  FOR SELECT TO authenticated USING (
    EXISTS (
      SELECT 1 FROM public.support_tickets t
      WHERE t.id = ticket_id
        AND (t.user_id = public.current_profile_id() OR public.is_admin())
    )
  );

CREATE TABLE IF NOT EXISTS public.buyer_protection_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference text NOT NULL UNIQUE,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  buyer_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  reason text NOT NULL,
  status text NOT NULL DEFAULT 'OPEN'
    CHECK (status IN ('OPEN','REVIEWING','APPROVED','REJECTED','CLOSED')),
  resolution text NOT NULL DEFAULT '',
  reviewed_by bigint REFERENCES public.profiles(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_protection_claims_buyer_created
  ON public.buyer_protection_claims(buyer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_protection_claims_status_created
  ON public.buyer_protection_claims(status, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_protection_claims_one_open_per_order
  ON public.buyer_protection_claims(order_id) WHERE status IN ('OPEN','REVIEWING');
ALTER TABLE public.buyer_protection_claims ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS protection_claims_buyer_read ON public.buyer_protection_claims;
CREATE POLICY protection_claims_buyer_read ON public.buyer_protection_claims
  FOR SELECT TO authenticated USING (buyer_id = public.current_profile_id() OR public.is_admin());

CREATE OR REPLACE FUNCTION public.list_my_buyer_addresses()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_profile_id bigint; v_result jsonb;
BEGIN
  v_profile_id := public.current_profile_id();
  IF v_profile_id IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
  SELECT coalesce(jsonb_agg(to_jsonb(x) ORDER BY x.is_default DESC, x.updated_at DESC), '[]'::jsonb)
    INTO v_result
  FROM (
    SELECT * FROM public.buyer_addresses
    WHERE profile_id = v_profile_id
    ORDER BY is_default DESC, updated_at DESC
  ) x;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.save_my_buyer_address(p_payload jsonb, p_address_id bigint DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_profile_id bigint; v_row public.buyer_addresses%ROWTYPE; v_default boolean;
BEGIN
  v_profile_id := public.current_profile_id();
  IF v_profile_id IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
  IF jsonb_typeof(p_payload) <> 'object' THEN RAISE EXCEPTION 'Invalid address'; END IF;
  IF length(trim(coalesce(p_payload->>'contact_name',''))) = 0
    OR length(trim(coalesce(p_payload->>'phone',''))) = 0
    OR length(trim(coalesce(p_payload->>'state',''))) = 0
    OR length(trim(coalesce(p_payload->>'city',''))) = 0
    OR length(trim(coalesce(p_payload->>'street',''))) = 0 THEN
    RAISE EXCEPTION 'Contact name, phone, state, city and street are required';
  END IF;
  v_default := coalesce((p_payload->>'is_default')::boolean, false);
  IF v_default THEN
    UPDATE public.buyer_addresses SET is_default = false, updated_at = now()
    WHERE profile_id = v_profile_id AND (p_address_id IS NULL OR id <> p_address_id) AND is_default;
  END IF;

  IF p_address_id IS NULL THEN
    INSERT INTO public.buyer_addresses(
      profile_id,label,contact_name,phone,state,city,area,street,landmark,instructions,lat,lng,is_default
    ) VALUES (
      v_profile_id,
      left(coalesce(nullif(trim(p_payload->>'label'),''),'Home'),40),
      left(trim(p_payload->>'contact_name'),100),
      left(trim(p_payload->>'phone'),30),
      left(trim(p_payload->>'state'),80),
      left(trim(p_payload->>'city'),80),
      left(coalesce(p_payload->>'area',''),100),
      left(trim(p_payload->>'street'),240),
      left(coalesce(p_payload->>'landmark',''),160),
      left(coalesce(p_payload->>'instructions',''),500),
      CASE WHEN nullif(p_payload->>'lat','') IS NULL THEN NULL ELSE (p_payload->>'lat')::double precision END,
      CASE WHEN nullif(p_payload->>'lng','') IS NULL THEN NULL ELSE (p_payload->>'lng')::double precision END,
      v_default
    ) RETURNING * INTO v_row;
  ELSE
    UPDATE public.buyer_addresses SET
      label=left(coalesce(nullif(trim(p_payload->>'label'),''),'Home'),40),
      contact_name=left(trim(p_payload->>'contact_name'),100),
      phone=left(trim(p_payload->>'phone'),30),
      state=left(trim(p_payload->>'state'),80),
      city=left(trim(p_payload->>'city'),80),
      area=left(coalesce(p_payload->>'area',''),100),
      street=left(trim(p_payload->>'street'),240),
      landmark=left(coalesce(p_payload->>'landmark',''),160),
      instructions=left(coalesce(p_payload->>'instructions',''),500),
      lat=CASE WHEN nullif(p_payload->>'lat','') IS NULL THEN NULL ELSE (p_payload->>'lat')::double precision END,
      lng=CASE WHEN nullif(p_payload->>'lng','') IS NULL THEN NULL ELSE (p_payload->>'lng')::double precision END,
      is_default=v_default, updated_at=now()
    WHERE id=p_address_id AND profile_id=v_profile_id
    RETURNING * INTO v_row;
    IF NOT FOUND THEN RAISE EXCEPTION 'Address not found'; END IF;
  END IF;
  RETURN to_jsonb(v_row);
END;
$$;

CREATE OR REPLACE FUNCTION public.delete_my_buyer_address(p_address_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_profile_id bigint; v_deleted bigint;
BEGIN
  v_profile_id := public.current_profile_id();
  IF v_profile_id IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
  DELETE FROM public.buyer_addresses WHERE id=p_address_id AND profile_id=v_profile_id RETURNING id INTO v_deleted;
  IF v_deleted IS NULL THEN RAISE EXCEPTION 'Address not found'; END IF;
  RETURN jsonb_build_object('success',true);
END;
$$;

CREATE OR REPLACE FUNCTION public.list_my_support_tickets()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_profile_id bigint; v_result jsonb;
BEGIN
  v_profile_id := public.current_profile_id();
  IF v_profile_id IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
  SELECT coalesce(jsonb_agg(
    to_jsonb(t) || jsonb_build_object(
      'support_ticket_messages',
      coalesce((SELECT jsonb_agg(to_jsonb(m) ORDER BY m.created_at ASC)
        FROM public.support_ticket_messages m WHERE m.ticket_id=t.id),'[]'::jsonb)
    ) ORDER BY t.updated_at DESC
  ),'[]'::jsonb)
  INTO v_result
  FROM (
    SELECT * FROM public.support_tickets
    WHERE user_id=v_profile_id ORDER BY updated_at DESC LIMIT 50
  ) t;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_my_support_ticket(
  p_category text,p_subject text,p_description text,p_order_id bigint DEFAULT NULL,p_priority text DEFAULT 'NORMAL'
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_profile_id bigint; v_name text; v_ticket public.support_tickets%ROWTYPE; v_priority text;
BEGIN
  v_profile_id := public.current_profile_id();
  IF v_profile_id IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
  IF p_category NOT IN ('PAYMENT','DELIVERY','ACCOUNT','REFUND','SELLER_DISPUTE','OTHER') THEN RAISE EXCEPTION 'Choose a valid category'; END IF;
  IF length(trim(coalesce(p_subject,''))) < 4 OR length(trim(coalesce(p_description,''))) < 10 THEN
    RAISE EXCEPTION 'Subject and a 10+ character description are required';
  END IF;
  IF p_order_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.orders WHERE id=p_order_id AND (buyer_id=v_profile_id OR seller_id=v_profile_id)
  ) THEN RAISE EXCEPTION 'Order does not belong to your account'; END IF;

  SELECT full_name INTO v_name FROM public.profiles WHERE id=v_profile_id;
  v_priority := CASE WHEN p_priority IN ('LOW','NORMAL','HIGH') THEN p_priority ELSE 'NORMAL' END;
  IF EXISTS (
    SELECT 1 FROM public.business_subscriptions
    WHERE user_id=v_profile_id AND plan IN ('PREMIUM','ENTERPRISE') AND expires_at>now()
  ) THEN v_priority := 'HIGH'; END IF;

  INSERT INTO public.support_tickets(reference,user_id,user_name,category,subject,description,order_id,status,priority)
  VALUES (
    'GS-TKT-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,10)),
    v_profile_id,coalesce(v_name,''),p_category,left(trim(p_subject),160),left(trim(p_description),10000),
    p_order_id,'OPEN',v_priority
  ) RETURNING * INTO v_ticket;

  INSERT INTO public.support_ticket_messages(ticket_id,author_id,author_name,author_role,body)
  VALUES (v_ticket.id,v_profile_id,coalesce(v_name,''),'BUYER',left(trim(p_description),10000));

  RETURN jsonb_build_object('id',v_ticket.id,'reference',v_ticket.reference);
END;
$$;

CREATE OR REPLACE FUNCTION public.list_my_buyer_protection_claims()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_profile_id bigint; v_result jsonb;
