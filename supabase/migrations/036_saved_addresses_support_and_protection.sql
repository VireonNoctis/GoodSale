  SELECT coalesce(jsonb_agg(to_jsonb(c) ORDER BY c.created_at DESC),'[]'::jsonb)
  INTO v_result FROM public.buyer_protection_claims c WHERE c.buyer_id=v_profile_id;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.open_my_buyer_protection_claim(p_order_id bigint,p_reason text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_profile_id bigint; v_order public.orders%ROWTYPE; v_claim public.buyer_protection_claims%ROWTYPE;
BEGIN
  v_profile_id:=public.current_profile_id();
  IF v_profile_id IS NULL THEN RAISE EXCEPTION 'Not authenticated'; END IF;
  IF p_order_id IS NULL OR p_order_id<=0 OR length(trim(coalesce(p_reason,'')))<15 THEN
    RAISE EXCEPTION 'Order and a 15+ character claim reason are required';
  END IF;
  SELECT * INTO v_order FROM public.orders WHERE id=p_order_id FOR UPDATE;
  IF NOT FOUND OR v_order.buyer_id<>v_profile_id THEN RAISE EXCEPTION 'Order not found'; END IF;
  IF NOT coalesce(v_order.has_good_sale_protect,false) THEN RAISE EXCEPTION 'GoodSale Protect was not purchased for this order'; END IF;
  IF v_order.status NOT IN ('PAID_ESCROW','SHIPPED','OUT_FOR_DELIVERY','PARTIAL_DEPOSIT_PAID','DELIVERED_SUCCESS') THEN
    RAISE EXCEPTION 'This order is not eligible for a protection claim';
  END IF;
  IF EXISTS(SELECT 1 FROM public.buyer_protection_claims WHERE order_id=p_order_id AND status IN ('OPEN','REVIEWING')) THEN
    RAISE EXCEPTION 'A claim is already under review';
  END IF;
  INSERT INTO public.buyer_protection_claims(reference,order_id,buyer_id,reason)
  VALUES ('GSPC-'||to_char(clock_timestamp(),'YYYYMMDDHH24MISS')||'-'||p_order_id,p_order_id,v_profile_id,left(trim(p_reason),1000))
  RETURNING * INTO v_claim;
  INSERT INTO public.notifications(user_id,title,message,type,is_read) VALUES
    (v_profile_id,'GoodSale Protect claim received','Claim '||v_claim.reference||' is under priority review.','ESCROW',false),
    (v_order.seller_id,'GoodSale Protect claim opened','Buyer opened claim '||v_claim.reference||' on '||v_order.order_number||'.','ESCROW',false);
  INSERT INTO public.audit_logs(user_id,action,entity_type,entity_id,details)
  VALUES(v_profile_id,'OPEN_BUYER_PROTECTION_CLAIM','ORDER',p_order_id,v_claim.reference||': '||left(p_reason,300));
  RETURN jsonb_build_object('id',v_claim.id,'reference',v_claim.reference,'status',v_claim.status,'created_at',v_claim.created_at);
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_list_buyer_protection_claims()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_result jsonb;
BEGIN
  IF coalesce(current_setting('request.jwt.claim.role', true), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Service role required';
  END IF;
  SELECT coalesce(jsonb_agg(to_jsonb(c) ORDER BY c.created_at DESC),'[]'::jsonb)
  INTO v_result FROM public.buyer_protection_claims c;
  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_review_buyer_protection_claim(p_claim_id bigint,p_status text,p_resolution text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_claim public.buyer_protection_claims%ROWTYPE; v_admin_id bigint;
BEGIN
  IF coalesce(current_setting('request.jwt.claim.role', true), '') <> 'service_role' THEN
    RAISE EXCEPTION 'Service role required';
  END IF;
  IF p_status NOT IN ('REVIEWING','APPROVED','REJECTED','CLOSED') THEN RAISE EXCEPTION 'Valid claim decision required'; END IF;
  IF p_status IN ('APPROVED','REJECTED') AND length(trim(coalesce(p_resolution,'')))<5 THEN RAISE EXCEPTION 'Add a decision note'; END IF;
  UPDATE public.buyer_protection_claims SET status=p_status,resolution=left(coalesce(p_resolution,''),1000),
    reviewed_at=now(),updated_at=now()
  WHERE id=p_claim_id RETURNING * INTO v_claim;
  IF NOT FOUND THEN RAISE EXCEPTION 'Claim not found'; END IF;
  SELECT id INTO v_admin_id FROM public.profiles
  WHERE auth_id=nullif(current_setting('request.jwt.claim.sub', true),'')::uuid LIMIT 1;
  INSERT INTO public.notifications(user_id,title,message,type,is_read)
  VALUES(v_claim.buyer_id,'GoodSale Protect claim updated',
    v_claim.reference||': '||lower(p_status)||CASE WHEN p_resolution<>'' THEN ' — '||left(p_resolution,500) ELSE '' END,
    'ESCROW',false);
  INSERT INTO public.audit_logs(user_id,action,entity_type,entity_id,details)
  VALUES(v_admin_id,'REVIEW_BUYER_PROTECTION_CLAIM','ORDER',v_claim.order_id,v_claim.reference||': '||p_status||' '||left(coalesce(p_resolution,''),500));
  RETURN jsonb_build_object('success',true,'claimId',v_claim.id);
END;
$$;

